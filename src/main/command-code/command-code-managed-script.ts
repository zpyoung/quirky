import { buildWindowsAgentHookPostCommand } from '../agent-hooks/installer-utils'
import {
  buildPosixHookPayloadCapture,
  buildPosixHookSpoolLines,
  buildWindowsHookEnvironmentGuardLines,
  buildWindowsHookStdinDrainEpilogue
} from '../agent-hooks/hook-stdin-contract'

export type CommandCodeManagedScriptTarget = 'local' | 'posix'

export function buildCommandCodeManagedScript(
  target: CommandCodeManagedScriptTarget = 'local'
): string {
  if (target === 'local' && process.platform === 'win32') {
    return [
      '@echo off',
      'setlocal',
      'if "%QUIRKY_AGENT_HOOK_PORT%"=="" if defined QUIRKY_AGENT_HOOK_ENDPOINT if exist "%QUIRKY_AGENT_HOOK_ENDPOINT%" call "%QUIRKY_AGENT_HOOK_ENDPOINT%" 2>nul',
      'if "%QUIRKY_AGENT_HOOK_TOKEN%"=="" if not "%QUIRKY_AGENT_HOOK_PORT%"=="" call :sourceEndpointByPort',
      ...buildWindowsHookEnvironmentGuardLines(),
      buildWindowsAgentHookPostCommand('command-code'),
      'exit /b 0',
      ':sourceEndpointByPort',
      'if not defined APPDATA exit /b 0',
      'if exist "%APPDATA%\\quirky-dev\\agent-hooks" for /r "%APPDATA%\\quirky-dev\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'if "%QUIRKY_AGENT_HOOK_TOKEN%"=="" if exist "%APPDATA%\\quirky\\agent-hooks" for /r "%APPDATA%\\quirky\\agent-hooks" %%F in (endpoint.cmd) do call :maybeSourceEndpoint "%%~fF"',
      'exit /b 0',
      ':maybeSourceEndpoint',
      'if not "%QUIRKY_AGENT_HOOK_TOKEN%"=="" exit /b 0',
      'for /f "tokens=2 delims==" %%P in (\'findstr /b /c:"set QUIRKY_AGENT_HOOK_PORT=" "%~1" 2^>nul\') do if "%%P"=="%QUIRKY_AGENT_HOOK_PORT%" call "%~1" 2>nul',
      'exit /b 0',
      ...buildWindowsHookStdinDrainEpilogue(),
      ''
    ].join('\r\n')
  }

  return [
    '#!/bin/sh',
    ...buildPosixHookPayloadCapture(),
    ...buildPosixHookSpoolLines('command-code'),
    '__quirky_read_ancestor_var() {',
    '  __quirky_name="$1"',
    '  __quirky_pid="${PPID:-}"',
    '  while [ -n "$__quirky_pid" ] && [ "$__quirky_pid" != "0" ] && [ "$__quirky_pid" != "1" ]; do',
    '    __quirky_value=""',
    '    if [ -r "/proc/$__quirky_pid/environ" ]; then',
    '      __quirky_value=$(tr "\\000" "\\n" < "/proc/$__quirky_pid/environ" 2>/dev/null | sed -n "s/^${__quirky_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -z "$__quirky_value" ]; then',
    '      __quirky_value=$(ps eww -p "$__quirky_pid" -o command= 2>/dev/null | tr " " "\\n" | sed -n "s/^${__quirky_name}=//p" | head -n 1)',
    '    fi',
    '    if [ -n "$__quirky_value" ]; then',
    '      printf "%s\\n" "$__quirky_value"',
    '      return 0',
    '    fi',
    '    __quirky_pid=$(ps -o ppid= -p "$__quirky_pid" 2>/dev/null | tr -d " ")',
    '  done',
    '  return 1',
    '}',
    '__quirky_fill_from_ancestor() {',
    '  __quirky_name="$1"',
    '  case "$__quirky_name" in',
    '    QUIRKY_AGENT_HOOK_ENDPOINT) [ -z "${QUIRKY_AGENT_HOOK_ENDPOINT:-}" ] || return 0 ;;',
    '    QUIRKY_AGENT_HOOK_PORT) [ -z "${QUIRKY_AGENT_HOOK_PORT:-}" ] || return 0 ;;',
    '    QUIRKY_AGENT_HOOK_TOKEN) [ -z "${QUIRKY_AGENT_HOOK_TOKEN:-}" ] || return 0 ;;',
    '    QUIRKY_AGENT_HOOK_ENV) [ -z "${QUIRKY_AGENT_HOOK_ENV:-}" ] || return 0 ;;',
    '    QUIRKY_AGENT_HOOK_VERSION) [ -z "${QUIRKY_AGENT_HOOK_VERSION:-}" ] || return 0 ;;',
    '    QUIRKY_PANE_KEY) [ -z "${QUIRKY_PANE_KEY:-}" ] || return 0 ;;',
    '    QUIRKY_TAB_ID) [ -z "${QUIRKY_TAB_ID:-}" ] || return 0 ;;',
    '    QUIRKY_WORKTREE_ID) [ -z "${QUIRKY_WORKTREE_ID:-}" ] || return 0 ;;',
    '    QUIRKY_AGENT_LAUNCH_TOKEN) [ -z "${QUIRKY_AGENT_LAUNCH_TOKEN:-}" ] || return 0 ;;',
    '    *) return 0 ;;',
    '  esac',
    '  __quirky_value=$(__quirky_read_ancestor_var "$__quirky_name") || return 0',
    '  [ -n "$__quirky_value" ] && export "$__quirky_name=$__quirky_value"',
    '}',
    '__quirky_endpoint_value() {',
    '  __quirky_endpoint_name="$1"',
    '  __quirky_endpoint_path="$2"',
    '  sed -n "s/^${__quirky_endpoint_name}=//p" "$__quirky_endpoint_path" 2>/dev/null | head -n 1',
    '}',
    '__quirky_fill_from_endpoint_file() {',
    '  __quirky_endpoint_path="$1"',
    '  [ -r "$__quirky_endpoint_path" ] || return 0',
    '  __quirky_endpoint_port=$(__quirky_endpoint_value QUIRKY_AGENT_HOOK_PORT "$__quirky_endpoint_path")',
    '  if [ -n "${QUIRKY_AGENT_HOOK_PORT:-}" ] && [ -n "$__quirky_endpoint_port" ] && [ "$__quirky_endpoint_port" != "$QUIRKY_AGENT_HOOK_PORT" ]; then',
    '    return 0',
    '  fi',
    '  for __quirky_endpoint_name in QUIRKY_AGENT_HOOK_PORT QUIRKY_AGENT_HOOK_TOKEN QUIRKY_AGENT_HOOK_ENV QUIRKY_AGENT_HOOK_VERSION; do',
    '    eval "__quirky_current=\\${$__quirky_endpoint_name:-}"',
    '    [ -z "$__quirky_current" ] || continue',
    '    __quirky_endpoint_value=$(__quirky_endpoint_value "$__quirky_endpoint_name" "$__quirky_endpoint_path")',
    '    [ -n "$__quirky_endpoint_value" ] && export "$__quirky_endpoint_name=$__quirky_endpoint_value"',
    '  done',
    '}',
    '# Why: Command Code sanitizes hook subprocess env. The parent TUI process',
    '# still has Quirky pane/hook metadata, so recover it before posting.',
    'for __quirky_name in QUIRKY_AGENT_HOOK_ENDPOINT QUIRKY_AGENT_HOOK_PORT QUIRKY_AGENT_HOOK_TOKEN QUIRKY_AGENT_HOOK_ENV QUIRKY_AGENT_HOOK_VERSION QUIRKY_PANE_KEY QUIRKY_TAB_ID QUIRKY_WORKTREE_ID QUIRKY_AGENT_LAUNCH_TOKEN; do',
    '  __quirky_fill_from_ancestor "$__quirky_name"',
    'done',
    'if [ -n "$QUIRKY_AGENT_HOOK_ENDPOINT" ] && [ -r "$QUIRKY_AGENT_HOOK_ENDPOINT" ]; then',
    '  __quirky_fill_from_endpoint_file "$QUIRKY_AGENT_HOOK_ENDPOINT"',
    'fi',
    '# Why: Command Code strips TOKEN-like env vars before invoking hooks. If',
    '# QUIRKY_AGENT_HOOK_ENDPOINT was not exported into this PTY, recover the',
    '# matching endpoint file by the unstripped loopback port.',
    'if [ -z "$QUIRKY_AGENT_HOOK_TOKEN" ] && [ -n "$QUIRKY_AGENT_HOOK_PORT" ]; then',
    '  for endpoint in \\',
    '    "$HOME/Library/Application Support/quirky-dev/agent-hooks"/*/endpoint.env \\',
    '    "$HOME/Library/Application Support/quirky-dev/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/quirky-dev/agent-hooks"/*/endpoint.env \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/quirky-dev/agent-hooks/endpoint.env" \\',
    '    "$HOME/Library/Application Support/quirky/agent-hooks/endpoint.env" \\',
    '    "${XDG_CONFIG_HOME:-$HOME/.config}/quirky/agent-hooks/endpoint.env"; do',
    '    [ -r "$endpoint" ] || continue',
    '    endpoint_port=$(sed -n "s/^QUIRKY_AGENT_HOOK_PORT=//p" "$endpoint" | head -n 1)',
    '    if [ "$endpoint_port" = "$QUIRKY_AGENT_HOOK_PORT" ]; then',
    '      __quirky_fill_from_endpoint_file "$endpoint"',
    '      break',
    '    fi',
    '  done',
    'fi',
    'if [ -z "$QUIRKY_AGENT_HOOK_PORT" ] || [ -z "$QUIRKY_AGENT_HOOK_TOKEN" ] || [ -z "$QUIRKY_PANE_KEY" ]; then',
    '  spool_hook_event',
    '  exit 0',
    'fi',
    // Timeout caps best-effort hook posts if the local listener stalls.
    // Why: pipe payload to curl's stdin (`payload@-`) instead of an inline
    // `payload=$VALUE` arg, so tens-of-KB tool output stays off the curl
    // command line (EDR command-line false positives). Wire body is identical.
    'printf \'%s\' "$payload" | curl -sS -X POST "http://127.0.0.1:${QUIRKY_AGENT_HOOK_PORT}/hook/command-code" \\',
    '  --connect-timeout 0.5 --max-time 1.5 \\',
    '  -H "Content-Type: application/x-www-form-urlencoded" \\',
    '  -H "X-Quirky-Agent-Hook-Token: ${QUIRKY_AGENT_HOOK_TOKEN}" \\',
    '  --data-urlencode "paneKey=${QUIRKY_PANE_KEY}" \\',
    '  --data-urlencode "tabId=${QUIRKY_TAB_ID}" \\',
    '  --data-urlencode "launchToken=${QUIRKY_AGENT_LAUNCH_TOKEN}" \\',
    '  --data-urlencode "worktreeId=${QUIRKY_WORKTREE_ID}" \\',
    '  --data-urlencode "env=${QUIRKY_AGENT_HOOK_ENV}" \\',
    '  --data-urlencode "version=${QUIRKY_AGENT_HOOK_VERSION}" \\',
    '  --data-urlencode "payload@-" >/dev/null 2>&1 || spool_hook_event',
    'exit 0',
    ''
  ].join('\n')
}
