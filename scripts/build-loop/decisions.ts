#!/usr/bin/env bun
/**
 * Rebuilds docs/loop/DECISIONS.md from the per-item logs in docs/loop/decisions/, hardest to
 * reverse and least confident first, so a reviewer reads the riskiest calls first.
 *
 *   bun scripts/build-loop/decisions.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, resolve } from 'node:path'

export type Decision = {
  item: string
  id: string
  title: string
  reversibility: string
  confidence: string
  source: string
}

const RANK: Record<string, number> = { hard: 0, low: 0, medium: 1, easy: 2, high: 2 }
const BUILD_DIR = resolve(import.meta.dir, '../../docs/loop')

/** Reads `## D<n>: title` entries and their `- **Field:** value` lines from one item's log. */
export function parse(item: string, text: string): Decision[] {
  const decisions: Decision[] = []
  for (const block of text.split(/^## /m).slice(1)) {
    const heading = block.match(/^(D\d+):\s*(.+)$/m)
    if (!heading) continue
    const field = (name: string) => block.match(new RegExp(`^- \\*\\*${name}:\\*\\*\\s*(.+)$`, 'mi'))?.[1].trim() ?? '?'
    decisions.push({
      item,
      id: heading[1],
      title: heading[2].trim(),
      reversibility: field('Reversibility').toLowerCase(),
      confidence: field('Confidence').toLowerCase(),
      source: field('Source'),
    })
  }
  return decisions
}

export function sortForReview(decisions: Decision[]): Decision[] {
  const rank = (value: string) => RANK[value.split(/\s/)[0]] ?? -1
  return [...decisions].sort(
    (a, b) => rank(a.reversibility) - rank(b.reversibility) || rank(a.confidence) - rank(b.confidence)
  )
}

export function render(decisions: Decision[]): string {
  const rows = sortForReview(decisions).map(
    (d) => `| ${d.reversibility} | ${d.confidence} | [${d.item} ${d.id}](decisions/${d.item}.md) | ${d.title} | ${d.source} |`
  )
  return [
    '# Decisions to review',
    '',
    'Every decision the build loop made without you, hardest to reverse and least confident first.',
    'Generated by `bun scripts/build-loop/decisions.ts` from `docs/loop/decisions/`; edit those',
    'files, not this one.',
    '',
    '| Reversibility | Confidence | Entry | Decision | Source |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n')
}

function main(): number {
  const dir = resolve(BUILD_DIR, 'decisions')
  const decisions = readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .flatMap((name) => parse(basename(name, '.md'), readFileSync(resolve(dir, name), 'utf8')))
  writeFileSync(resolve(BUILD_DIR, 'DECISIONS.md'), render(decisions))
  return 0
}

if (import.meta.main) process.exit(main())
