import { useCallback, useEffect, useRef, useState } from 'react'
import { Badge, Button, SectionHeader, ToolPanelFrame } from '@quirky/ui'
import type { MobilePairingResult, UiPluginContext } from '@quirky/protocol'
import { createPairing } from './api'
import { DeviceList } from './DeviceList'
import { pairedDateLabel } from './date'
import { NetworkPicker } from './NetworkPicker'
import { PairingPanel } from './PairingPanel'
import { useMobileState } from './useMobileState'

export const MOBILE_PAGE_ID = 'view:quirky.mobile/page'
export const MOBILE_SETTINGS_ID = 'view:quirky.mobile/settings'

type Stage = 'intro' | 'install' | 'pair' | 'paired'

export type MobilePageInput = {
  stage?: Stage
  platform?: 'iOS' | 'Android'
  channel?: 'Preview' | 'Stable'
  address?: string
}

function pageInput(input: unknown): MobilePageInput {
  if (!input || typeof input !== 'object') return {}
  const result: MobilePageInput = {}
  if ('stage' in input && (input.stage === 'intro' || input.stage === 'install' || input.stage === 'pair' || input.stage === 'paired')) result.stage = input.stage
  if ('platform' in input && (input.platform === 'iOS' || input.platform === 'Android')) result.platform = input.platform
  if ('channel' in input && (input.channel === 'Preview' || input.channel === 'Stable')) result.channel = input.channel
  if ('address' in input && typeof input.address === 'string') result.address = input.address
  return result
}

function messageOf(error: unknown): string {
  return error instanceof Error ? error.message : String(error)
}

export function MobilePage({ context, input, report }: { context: UiPluginContext; input?: unknown; report?(state: unknown): void }) {
  const mobile = useMobileState(context)
  const [initial] = useState(() => pageInput(input))
  const [stage, setStage] = useState<Stage | null>(initial.stage ?? null)
  const [platform, setPlatform] = useState<'iOS' | 'Android'>(initial.platform ?? 'iOS')
  const [channel, setChannel] = useState<'Preview' | 'Stable'>(initial.channel ?? 'Preview')
  const [selectedAddress, setSelectedAddress] = useState(initial.address ?? '')
  const [offer, setOffer] = useState<MobilePairingResult | null>(null)
  const [busy, setBusy] = useState(false)
  const [offerVisible, setOfferVisible] = useState(false)
  const [baselineCount, setBaselineCount] = useState<number | null>(null)
  const [actionError, setActionError] = useState<string | null>(null)
  const autoGenerated = useRef(false)

  useEffect(() => {
    report?.({
      stage: stage ?? 'intro', platform, channel, address: selectedAddress, busy,
      pairingAvailable: offer?.available ?? false,
      devices: mobile.state?.devices.map((device) => ({ ...device, pairedLabel: pairedDateLabel(device.pairedAt) })) ?? [],
      error: actionError ?? mobile.error
    })
  }, [report, stage, platform, channel, selectedAddress, busy, offer?.available, mobile.state?.devices, mobile.error, actionError])

  useEffect(() => {
    if (stage === null && mobile.state) setStage(mobile.state.devices.length > 0 ? 'paired' : mobile.state.onboardingSeen ? 'install' : 'intro')
  }, [mobile.state, stage])

  useEffect(() => {
    if (!mobile.state || selectedAddress) return
    setSelectedAddress(mobile.state.interfaces[0]?.address ?? mobile.state.customAddresses[0] ?? '')
  }, [mobile.state, selectedAddress])


  useEffect(() => {
    if (!offerVisible) return
    const refresh = () => void mobile.refreshDevices().catch((error: unknown) => setActionError(messageOf(error)))
    refresh()
    const timer = window.setInterval(refresh, 3000)
    return () => window.clearInterval(timer)
  }, [mobile.refreshDevices, offerVisible])

  useEffect(() => {
    if (!offerVisible || baselineCount === null || mobile.state === null || mobile.state.devices.length <= baselineCount) return
    setStage('paired')
    setOfferVisible(false)
    if (!mobile.state.onboardingSeen) void mobile.configure({ onboardingSeen: true }).catch((error: unknown) => setActionError(messageOf(error)))
  }, [baselineCount, mobile.configure, mobile.state?.devices.length, mobile.state?.onboardingSeen, offerVisible])

  const generate = useCallback(async (rotate: boolean) => {
    const currentState = mobile.state
    if (currentState === null) return
    setBusy(true)
    setActionError(null)
    setOfferVisible(false)
    setOffer(null)
    try {
      const devices = await mobile.refreshDevices()
      if (!rotate) setBaselineCount(devices.length)
      const address = selectedAddress || currentState.interfaces[0]?.address || currentState.customAddresses[0]
      const result = await createPairing(context, address, rotate)
      setOffer(result)
      setOfferVisible(result.available)
      setActionError(null)
    } catch (error) {
      setActionError(messageOf(error))
    } finally {
      setBusy(false)
    }
  }, [context, mobile.refreshDevices, mobile.state, selectedAddress])

  useEffect(() => {
    if (stage !== 'pair') {
      autoGenerated.current = false
      return
    }
    if (!mobile.state || autoGenerated.current) return
    autoGenerated.current = true
    void generate(false)
  }, [stage, mobile.state, generate])

  const startPairing = useCallback(() => {
    autoGenerated.current = false
    setOffer(null)
    setStage('pair')
  }, [])

  const saveOnboardingSeen = async () => {
    setStage('install')
    try {
      await mobile.configure({ onboardingSeen: true })
      setActionError(null)
    } catch (error) {
      setActionError(messageOf(error))
    }
  }

  const updateSidebar = async () => {
    if (!mobile.state) return
    try {
      await mobile.configure({ showMobileButton: !mobile.state.showMobileButton })
      setActionError(null)
    } catch (error) {
      setActionError(messageOf(error))
    }
  }

  const addAddress = async (address: string) => {
    const current = mobile.state
    if (!current) return
    if (current.customAddresses.includes(address)) {
      setSelectedAddress(address)
      return
    }
    if (current.customAddresses.length >= 50) throw new Error('You can save up to 50 custom addresses.')
    const next = await mobile.configure({ customAddresses: [...current.customAddresses, address] })
    setSelectedAddress(address)
    setActionError(null)
    if (!next.customAddresses.includes(address)) throw new Error('The address was not saved.')
  }

  const removeAddress = async (address: string) => {
    const current = mobile.state
    if (!current) return
    const next = await mobile.configure({ customAddresses: current.customAddresses.filter((item) => item !== address) })
    setSelectedAddress(next.interfaces[0]?.address ?? next.customAddresses[0] ?? '')
    setActionError(null)
  }

  const refreshInterfaces = async () => {
    try {
      const interfaces = await mobile.refreshInterfaces()
      if (!interfaces.some((item) => item.address === selectedAddress) && !mobile.state?.customAddresses.includes(selectedAddress)) {
        setSelectedAddress(interfaces[0]?.address ?? mobile.state?.customAddresses[0] ?? '')
      }
      setActionError(null)
    } catch (error) {
      setActionError(messageOf(error))
    }
  }

  if (mobile.loading && mobile.state === null) {
    return <main className="ui-panel-content ui-stack"><p role="status">Loading Mobile…</p></main>
  }
  if (mobile.state === null) {
    return (
      <main className="ui-panel-content ui-stack">
        <SectionHeader title="Mobile" />
        <p className="ui-error-text" role="alert">Unable to load Mobile settings: {mobile.error ?? 'The daemon returned no state.'}</p>
        <div className="ui-cluster"><Button onClick={() => void mobile.refresh()}>Try again</Button></div>
      </main>
    )
  }

  const currentStage = stage ?? 'intro'
  return (
    <main className="ui-panel-content ui-stack">
      <div className="ui-stack">
        <SectionHeader
          title="Mobile"
          actions={
            <>
              <Button onClick={() => context.openView(MOBILE_SETTINGS_ID)}>Settings</Button>
              <Button onClick={() => void updateSidebar()}>{mobile.state.showMobileButton ? 'Hide from sidebar' : 'Show in sidebar'}</Button>
            </>
          }
        />
        <p className="ui-text-muted">Control terminals and agents from your phone.</p>
      </div>
      {mobile.error && <p className="ui-error-text" role="alert">Could not refresh Mobile state: {mobile.error}</p>}
      {actionError && <p className="ui-error-text" role="alert">{actionError}</p>}

      {currentStage === 'intro' && (
        <ToolPanelFrame title="Your workspaces, in your pocket.">
          <div className="ui-stack">
            <p className="ui-text-muted">Pair Quirky Mobile directly with this desktop to watch sessions and control terminals.</p>
            <div className="ui-cluster"><Button variant="primary" onClick={() => void saveOnboardingSeen()}>Get started</Button></div>
          </div>
        </ToolPanelFrame>
      )}

      {currentStage === 'install' && (
        <ToolPanelFrame title="Get the app">
          <div className="ui-stack">
            <p className="ui-text-muted">Step 1 of 2</p>
            <p>Choose your phone platform and release channel.</p>
            <div className="ui-cluster" role="group" aria-label="Phone platform">
              {(['iOS', 'Android'] as const).map((choice) => (
                <Button key={choice} variant={platform === choice ? 'primary' : 'secondary'} aria-pressed={platform === choice} onClick={() => setPlatform(choice)}>{choice}</Button>
              ))}
            </div>
            <div className="ui-cluster" role="group" aria-label="Release channel">
              {(['Preview', 'Stable'] as const).map((choice) => (
                <Button key={choice} variant={channel === choice ? 'primary' : 'secondary'} aria-pressed={channel === choice} onClick={() => setChannel(choice)}>{choice}</Button>
              ))}
            </div>
            <p role="status"><Badge tone="needs-you">Unavailable</Badge> Quirky mobile app is not available yet for {platform} ({channel.toLowerCase()}). Orca’s hosted mobile app uses an incompatible RPC protocol and cannot pair with Quirky.</p>
            <div className="ui-cluster">
              <Button onClick={() => setStage('intro')}>Back</Button>
              <Button variant="primary" onClick={startPairing}>Continue</Button>
            </div>
          </div>
        </ToolPanelFrame>
      )}

      {currentStage === 'pair' && (
        <>
          <ToolPanelFrame title="Pair this desktop">
            <div className="ui-stack">
              <p className="ui-text-muted">Step 2 of 2</p>
              <p>Pairing uses the selected LAN or Tailscale address. Relay is unavailable in this build.</p>
              <NetworkPicker
                interfaces={mobile.state.interfaces}
                customAddresses={mobile.state.customAddresses}
                selectedAddress={selectedAddress}
                busy={busy}
                onSelect={setSelectedAddress}
                onRefresh={refreshInterfaces}
                onAdd={addAddress}
                onRemove={removeAddress}
              />
            </div>
          </ToolPanelFrame>
          <PairingPanel offer={offer} busy={busy} error={null} buttonLabel="Generate code" onGenerate={generate} />
          <div className="ui-cluster"><Button onClick={() => setStage('install')}>Back</Button></div>
        </>
      )}

      {currentStage === 'paired' && (
        <>
          <ToolPanelFrame title={mobile.state.devices.length > 0 ? 'Your phone is paired.' : 'No phones paired yet.'}>
            <p className="ui-text-muted">{mobile.state.devices.length > 0 ? 'Open Quirky Mobile to pick up where you left off, or pair another device.' : 'Pair a phone to connect this desktop to Quirky Mobile.'}</p>
          </ToolPanelFrame>
          <DeviceList context={context} devices={mobile.state.devices} onChanged={async () => { await mobile.refreshDevices() }} />
          <div className="ui-cluster"><Button variant="primary" onClick={startPairing}>Pair another device</Button></div>
        </>
      )}
      <div className="ui-cluster"><Button onClick={() => context.openView(MOBILE_SETTINGS_ID)}>Configure in Settings &gt; Mobile</Button></div>
    </main>
  )
}
