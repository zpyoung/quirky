const HARNESS_TAGS: Record<string, true> = {
  'agent-message': true,
  'bash-input': true,
  'bash-stderr': true,
  'bash-stdout': true,
  'command-args': true,
  'command-message': true,
  'command-name': true,
  'cross-session-message': true,
  'fork-boilerplate': true,
  'local-command-caveat': true,
  'local-command-stderr': true,
  'local-command-stdout': true,
  'mcp-polling-update': true,
  'mcp-resource-update': true,
  'system-reminder': true,
  'task-notification': true,
  'teammate-message': true,
  'user-memory-input': true,
  'user-prompt-submit-hook': true
}
const HARNESS_PREFIXES = [
  '<channel source=',
  '[request interrupted',
  'a message arrived from ',
  'another claude session sent a message',
  'no response requested.',
  'caveat: the messages below were generated by the user while running local commands',
  'this session is being continued from a previous conversation'
]
const CODEX_TOOL_TYPES: Record<string, true> = {
  function_call: true,
  local_shell_call: true,
  custom_tool_call: true,
  function_call_output: true,
  custom_tool_call_output: true
}
const CODEX_TOOL_INPUT_KEYS = ['command', 'cmd', 'file_path', 'path', 'pattern', 'query', 'description'] as const

/** Dispatch only the seven primary provider formats owned by this parser. */
export async function parsePrimary(context: ParserContext): Promise<VaultSession | null> {
  throwIfAborted(context.signal)
  switch (context.candidate.agent) {
    case 'claude':
      return parseClaude(context)
    case 'qoder':
      return parseQoder(context)
    case 'codebuddy':
      return parseCodeBuddy(context)
    case 'codex':
      return parseCodex(context)
    case 'gemini':
      return parseGemini(context)
    case 'copilot':
      return parseCopilot(context)
    case 'cursor':
      return parseCursor(context)
    default:
      return null
  }
}

function newBuilder(context: ParserContext): Builder {
  // These providers derive their title from transcript records or a named
  // sidecar. Suppress an unrelated discovery default until that precedence is
  // applied explicitly at finish.
  return createSessionBuilder({ ...context }, { title: '' })
}

function noteTime(builder: Builder, timestamp: unknown): void {
  builder.message('system', null, timestamp, false)
}

function countOnly(builder: Builder, timestamp: unknown): void {
  builder.message('tool', null, timestamp)
}

function emitUser(
  builder: Builder,
  text: string | null,
  timestamp: unknown,
  seedPrompt = true
): void {
  if (seedPrompt) {
    builder.message('user', text, timestamp)
    return
  }
  const firstPromptTitle = builder.firstPromptTitle
  const capturePrompts = builder.context.capturePrompts
  builder.context.capturePrompts = false
  try {
    builder.message('user', text, timestamp)
  } finally {
    builder.context.capturePrompts = capturePrompts
  }
  builder.firstPromptTitle = firstPromptTitle
}

function setSessionId(builder: Builder, value: unknown): void {
  const sessionId = string(value)
  if (sessionId) builder.patch({ sessionId })
}

function updateLocation(builder: Builder, record: Record<string, unknown>): void {
  if (builder.fields.cwd === null) {
    const cwd = string(record.cwd)
    if (cwd) builder.patch({ cwd })
  }
  const branch = string(record.gitBranch)
  if (branch) {
    const timestamp = numberOrDate(record.timestamp)
    if (timestamp === null || builder.fields.updatedAt === null || timestamp >= builder.fields.updatedAt) {
      builder.patch({ branch })
    }
  }
}

function titleText(value: unknown): string | null {
  return normalizeTitle(textFromContent(value))
}

function injectedUserText(value: string | null): boolean {
  if (!value) return false
  let start = 0
  const wsEnd = Math.min(value.length, 64)
  while (start < wsEnd && /[ \t\n\r\f]/.test(value[start])) start++
  const head = value.slice(start, start + 256).toLowerCase()
  const tag = /^<([a-z][a-z0-9-]*)(?:[\s>]|$)/.exec(head)?.[1]
  if (tag !== undefined && Object.hasOwn(HARNESS_TAGS, tag)) return true
  for (const prefix of HARNESS_PREFIXES) {
    if (head.startsWith(prefix)) return true
  }
  return false
}

type ClaudeState = {
  builder: Builder
  generatedTitle: string | null
  metaTitle: string | null
  customTitle: string | null
  queued: number
}

function parseClaudeState(context: ParserContext): ClaudeState {
  return {
    builder: newBuilder(context),
    generatedTitle: null,
    metaTitle: null,
    customTitle: null,
    queued: 0
  }
}

function consumeClaudeRecord(state: ClaudeState, record: Record<string, unknown>, qoder = false): void {
  const { builder } = state
  setSessionId(builder, record.sessionId)
  noteTime(builder, record.timestamp)
  updateLocation(builder, record)

  if (record.type === 'custom-title') {
    state.customTitle = normalizeTitle(string(record.customTitle))
    if (state.customTitle) builder.patch({ title: state.customTitle })
    else builder.fields.title = null
    return
  }
  if (record.type === 'ai-title') {
    state.generatedTitle = normalizeTitle(string(record.aiTitle)) ?? state.generatedTitle
    return
  }
  if (record.type === 'agent-name') {
    if (!state.generatedTitle) state.metaTitle ??= normalizeTitle(string(record.agentName))
    return
  }
  if (record.type === 'queue-operation') {
    if (record.operation === 'enqueue' && (string(record.content)?.length ?? 0) > 0) {
      state.queued++
    } else if (record.operation === 'remove' || record.operation === 'dequeue') {
      state.queued = Math.max(0, state.queued - 1)
    }
    builder.patch({ queuedMessageCount: state.queued })
    return
  }
  if (record.type === 'last-prompt') {
    const prompt = normalizeTitle(string(record.lastPrompt))
    if (prompt && builder.context.capturePrompts !== false) builder.lastUserPrompt = prompt
    return
  }

  const message = isRecord(record.message) ? record.message : null
  let content: unknown = message?.content
  if (qoder && message && Array.isArray(message.content)) {
    let text = ''
    for (const block of message.content) {
      if (!isRecord(block) || block.type !== 'text') continue
      text += textFromContent(block) ?? ''
      if (text.length > MAX_MESSAGE_CHARS) break
    }
    content = boundedText(text)
  }
  const text = textFromContent(content)
  if (record.type === 'user') {
    const title = titleText(content)
    const meta = record.isMeta === true || injectedUserText(title)
    if (meta && title) state.metaTitle ??= title
    emitUser(builder, text, record.timestamp, !meta)
    publishContentTools(builder.context, content, record.timestamp)
    return
  }
  if (record.type === 'assistant') {
    builder.message('assistant', text, record.timestamp)
    publishContentTools(builder.context, content, record.timestamp)
    const model = string(message?.model)
    if (model) builder.patch({ model })
    const usage = isRecord(message?.usage) ? message.usage : null
    if (usage) {
      builder.patch({
        totalTokens:
          numberValue(usage.input_tokens) +
          numberValue(usage.output_tokens) +
          numberValue(usage.cache_read_input_tokens) +
          numberValue(usage.cache_creation_input_tokens)
      })
    }
  }
}

async function parseClaude(context: ParserContext): Promise<VaultSession> {
  const state = parseClaudeState(context)
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    consumeClaudeRecord(state, record)
  }
  return state.builder.finish({
    titleFallback: state.generatedTitle ?? state.builder.firstPromptTitle ?? state.metaTitle
  })
}

async function parseQoder(context: ParserContext): Promise<VaultSession> {
  const state = parseClaudeState(context)
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    consumeClaudeRecord(state, record, true)
    if (record.type === 'workspace-directories' && state.builder.fields.cwd === null && Array.isArray(record.directories)) {
      const cwd = string(record.directories[0])
      if (cwd) state.builder.patch({ cwd })
    }
    if (record.type === 'runtime-config') {
      const model = string(record.model)
      if (model) state.builder.patch({ model })
      noteTime(state.builder, record.timestamp)
    }
  }
  return state.builder.finish({
    titleFallback: state.generatedTitle ?? state.builder.firstPromptTitle ?? state.metaTitle
  })
}

function codeBuddyText(content: unknown): string | null {
  if (typeof content === 'string') return boundedText(content)
  if (!Array.isArray(content)) return null
  let text = ''
  let found = false
  for (const block of content) {
    if (!isRecord(block) || (block.type !== 'input_text' && block.type !== 'output_text' && block.type !== 'text')) continue
    const part = string(block.text)
    if (!part) continue
    const separator = found ? '\n\n' : ''
    const remaining = MAX_MESSAGE_CHARS + 1 - text.length - separator.length
    if (remaining <= 0) break
    text += separator + part.slice(0, remaining)
    found = true
    if (part.length > remaining) break
  }
  return found ? boundedText(text) : null
}

async function parseCodeBuddy(context: ParserContext): Promise<VaultSession> {
  const builder = newBuilder(context)
  let summaryTitle: string | null = null
  let generatedTitle: string | null = null
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    setSessionId(builder, record.sessionId)
    noteTime(builder, record.timestamp)
    updateLocation(builder, record)
    if (record.type === 'summary') {
      summaryTitle = normalizeTitle(string(record.summary)) ?? summaryTitle
      if (summaryTitle) builder.patch({ title: summaryTitle })
      continue
    }
    if (record.type === 'ai-title') {
      generatedTitle = normalizeTitle(string(record.aiTitle)) ?? generatedTitle
      continue
    }
    if (record.type !== 'message') continue

    const role = string(record.role)
    const text = codeBuddyText(record.content)
    if (role === 'user') {
      const providerData = isRecord(record.providerData) ? record.providerData : null
      const meta = providerData?.skipRun === true || injectedUserText(text)
      emitUser(builder, text, record.timestamp, !meta)
    } else if (role === 'assistant') {
      builder.message('assistant', text, record.timestamp)
      const providerData = isRecord(record.providerData) ? record.providerData : null
      const model = string(providerData?.model)
      if (model) builder.patch({ model })
    } else {
      countOnly(builder, record.timestamp)
    }
  }
  return builder.finish({ titleFallback: generatedTitle ?? builder.firstPromptTitle })
}

function codexIndexPath(candidate: SourceCandidate): string | null {
  const metadataPath = string(candidate.metadata?.codexIndexPath)
  if (metadataPath) return metadataPath
  for (const sidecar of candidate.sidecars ?? []) {
    if (basename(sidecar) === 'session_index.jsonl') return sidecar
  }
  if (candidate.codexHome) return join(candidate.codexHome, 'session_index.jsonl')
  let directory = dirname(candidate.filePath)
  while (directory && dirname(directory) !== directory) {
    if (basename(directory) === 'sessions') return join(dirname(directory), 'session_index.jsonl')
    directory = dirname(directory)
  }
  return null
}

function codexUnionTag(value: unknown): string | null {
  const tag = string(value)
  if (tag) return tag
  if (!isRecord(value)) return null
  const keys = Object.keys(value)
  return keys.length === 1 ? string(keys[0]) : null
}

function isCodexNonUser(payload: Record<string, unknown>): boolean {
  const threadSource = string(payload.thread_source) ?? string(payload.threadSource)
  if (threadSource) return threadSource.toLowerCase() !== 'user'
  const source = codexUnionTag(payload.source)
  return source === 'subagent' || source === 'internal'
}

function codexBranch(value: unknown): string | null {
  if (!isRecord(value)) return null
  return string(value.branch) ?? string(value.current_branch)
}

function codexModel(value: unknown): string | null {
  if (!isRecord(value)) return null
  const metadata = isRecord(value.metadata) ? value.metadata : null
  const info = isRecord(value.info) ? value.info : null
  return string(value.model) ?? string(value.model_name) ?? string(metadata?.model) ?? string(info?.model)
}

function codexUsage(value: unknown): number | null {
  if (!isRecord(value)) return null
  const total = numberValue(value.total_tokens)
  return total > 0 ? total : numberValue(value.input_tokens) + numberValue(value.output_tokens)
}

function codexTitle(payload: Record<string, unknown>): string | null {
  return normalizeTitle(string(payload.title) ?? string(payload.thread_name) ?? string(payload.threadName))
}

function joinStringValues(values: unknown[]): string {
  let joined = ''
  let first = true
  for (const value of values) {
    if (typeof value !== 'string') continue
    if (!first) joined += ' '
    joined += value
    first = false
  }
  return joined
}

function codexToolCallText(name: unknown, input: unknown): string | null {
  const toolName = string(name)
  let argument: string | null = null
  if (isRecord(input)) {
    for (const key of CODEX_TOOL_INPUT_KEYS) {
      const candidate = string(input[key])
      if (candidate) {
        argument = candidate
        break
      }
    }
  } else {
    argument = string(input)
  }
  if (!toolName && !argument) return null
  return toolName && argument ? `${toolName}: ${argument.slice(0, 2000)}` : (toolName ?? argument?.slice(0, 2000) ?? null)
}

function codexToolResultText(content: unknown): string | null {
  if (typeof content === 'string') return boundedText(content)
  if (!Array.isArray(content)) return null
  let text = ''
  let found = false
  for (const item of content) {
    const part = typeof item === 'string' ? item : isRecord(item) && typeof item.text === 'string' ? item.text : null
    if (!part) continue
    const separator = found ? '\n' : ''
    const remaining = MAX_MESSAGE_CHARS + 1 - text.length - separator.length
    if (remaining <= 0) break
    text += separator + part.slice(0, remaining)
    found = true
    if (part.length > remaining) break
  }
  return found ? boundedText(text) : null
}

function publishTool(context: ParserContext, text: unknown, timestamp: unknown): void {
  const bounded = boundedText(text)
  if (!bounded) return
  context.onMessage?.({ role: 'tool', text: bounded, timestamp: numberOrDate(timestamp) })
}
function publishContentToolBlock(context: ParserContext, block: unknown, timestamp: unknown): void {
  if (!isRecord(block)) return
  const type = string(block.type)?.toLowerCase()
  if (type === 'tool_use') {
    publishTool(context, codexToolCallText(block.name, block.input), timestamp)
  } else if (type === 'tool_result') {
    publishTool(context, codexToolResultText(block.content), timestamp)
  }
}

function publishContentTools(context: ParserContext, content: unknown, timestamp: unknown): void {
  if (!context.onMessage) return
  if (Array.isArray(content)) {
    for (const block of content) publishContentToolBlock(context, block, timestamp)
  } else if (content !== null && content !== undefined) {
    publishContentToolBlock(context, content, timestamp)
  }
}

function publishCodexResponseTool(context: ParserContext, payload: Record<string, unknown>, timestamp: unknown): void {
  if (!Object.hasOwn(CODEX_TOOL_TYPES, String(payload.type))) return
  if (payload.type === 'function_call_output' || payload.type === 'custom_tool_call_output') {
    const output = isRecord(payload.output) ? payload.output : null
    publishTool(context, codexToolResultText(output?.content ?? output?.output ?? payload.output), timestamp)
    return
  }
  let input = payload.arguments ?? payload.input ?? payload.action
  const action = isRecord(input) ? input : null
  if (action && Array.isArray(action.command)) {
    input = joinStringValues(action.command)
  }
  publishTool(context, codexToolCallText(payload.name ?? 'tool', input), timestamp)
}

function publishCodexCompletedTool(context: ParserContext, payload: Record<string, unknown>, timestamp: unknown): void {
  const item = isRecord(payload.item) ? payload.item : null
  if (item?.type === 'CommandExecution' || item?.type === 'command_execution') {
    const command = Array.isArray(item.command) ? joinStringValues(item.command) : item.command
    publishTool(context, codexToolCallText('shell', command), timestamp)
    publishTool(context, item.aggregated_output ?? item.aggregatedOutput, timestamp)
    return
  }
  if (item?.type === 'FileChange' || item?.type === 'file_change') {
    const changes = isRecord(item.changes) ? item.changes : {}
    for (const path in changes) {
      if (!Object.hasOwn(changes, path)) continue
      const change = isRecord(changes[path]) ? changes[path] : null
      publishTool(context, codexToolCallText('apply_patch', { path }), timestamp)
      publishTool(context, change?.unified_diff ?? change?.content, timestamp)
    }
  }
}

async function findCodexIndexTitle(
  path: string,
  sessionId: string,
  context: ParserContext
): Promise<string | null> {
  let title: string | null = null
  try {
    for await (const record of readJsonl(path, context.signal)) {
      if (string(record.id) === sessionId) {
        title = normalizeTitle(string(record.thread_name)) ?? title
      }
    }
  } catch {
    throwIfAborted(context.signal)
    return null
  }
  return title
}

type CodexState = {
  builder: Builder
  previousUsage: number | null
  sawSessionMeta: boolean
  historyMode: string | null
  nonUserOrigin: boolean
  metaTitle: string | null
  userTitle: string | null
  indexTitle: string | null
}

function consumeCodexRecord(state: CodexState, context: ParserContext, record: Record<string, unknown>): void {
  const { builder } = state
  noteTime(builder, record.timestamp)
  const payload = isRecord(record.payload) ? record.payload : null
  if (record.type === 'session_meta' && payload && !state.sawSessionMeta) {
    if (isCodexNonUser(payload)) {
      state.nonUserOrigin = true
      return
    }
    state.sawSessionMeta = true
    state.historyMode = string(payload.history_mode)
    setSessionId(builder, payload.id)
    state.metaTitle = codexTitle(payload)
    if (state.metaTitle) builder.patch({ title: state.metaTitle })
    const cwd = string(payload.cwd)
    if (cwd) builder.patch({ cwd })
    const branch = codexBranch(payload.git)
    if (branch) builder.patch({ branch })
    return
  }
  if (record.type === 'turn_context' && payload) {
    const cwd = string(payload.cwd)
    if (cwd) builder.patch({ cwd })
    const model = codexModel(payload)
    if (model) builder.patch({ model })
    return
  }
  if (!payload) return

  if (record.type === 'response_item') {
    if (state.historyMode === 'paginated') return
    publishCodexResponseTool(context, payload, record.timestamp)
    if (payload.type !== 'message') return
    const role = payload.role === 'user' ? 'user' : payload.role === 'assistant' ? 'assistant' : null
    const text = textFromContent(payload.content)
    if (!role) {
      countOnly(builder, record.timestamp)
      publishContentTools(context, payload.content, record.timestamp)
      return
    }
    if (role === 'user' && !state.metaTitle && !state.indexTitle) {
      state.userTitle ??= normalizeTitle(text)
    }
    if (role === 'user') emitUser(builder, text, record.timestamp)
    else builder.message(role, text, record.timestamp)
    publishContentTools(context, payload.content, record.timestamp)
    return
  }

  if (record.type !== 'event_msg') return
  if (state.historyMode === 'paginated' && payload.type === 'item_completed') {
    publishCodexCompletedTool(context, payload, record.timestamp)
    const item = isRecord(payload.item) ? payload.item : null
    const role = item?.type === 'UserMessage' || item?.type === 'user_message'
      ? 'user'
      : item?.type === 'AgentMessage' || item?.type === 'agent_message'
        ? 'assistant'
        : null
    if (!role) return
    const text = textFromContent(item?.content)
    if (role === 'user' && !state.metaTitle && !state.indexTitle) {
      state.userTitle ??= normalizeTitle(text)
    }
    if (role === 'user') emitUser(builder, text, record.timestamp)
    else builder.message(role, text, record.timestamp)
    publishContentTools(context, item?.content, record.timestamp)
    return
  }
  if (payload.type === 'user_message' || payload.type === 'agent_message') {
    const role = payload.type === 'user_message' ? 'user' : 'assistant'
    const text = textFromContent(payload.message)
    if (role === 'user' && !state.metaTitle && !state.indexTitle) {
      state.userTitle ??= normalizeTitle(text)
    }
    if (role === 'user') emitUser(builder, text, record.timestamp)
    else builder.message(role, text, record.timestamp)
    publishContentTools(context, payload.message, record.timestamp)
    return
  }
  if (payload.type !== 'token_count') return
  const info = isRecord(payload.info) ? payload.info : null
  if (!info) return
  const totalUsage = codexUsage(info.total_token_usage)
  const lastUsage = codexUsage(info.last_token_usage)
  let delta = 0
  if (totalUsage !== null) {
    delta = Math.max(totalUsage - (state.previousUsage ?? 0), 0)
    state.previousUsage = totalUsage
  } else if (lastUsage !== null) {
    delta = lastUsage
    state.previousUsage = (state.previousUsage ?? 0) + lastUsage
  }
  if (delta) builder.patch({ totalTokens: delta })
  const model = codexModel(payload)
  if (model) builder.patch({ model })
}

async function parseCodex(context: ParserContext): Promise<VaultSession | null> {
  const builder = newBuilder(context)
  const candidateTitle = normalizeTitle(string(context.candidate.metadata?.title))
  const state: CodexState = {
    builder,
    previousUsage: null,
    sawSessionMeta: false,
    historyMode: null,
    nonUserOrigin: false,
    metaTitle: null,
    userTitle: null,
    indexTitle: candidateTitle
  }
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    consumeCodexRecord(state, context, record)
    if (state.nonUserOrigin) return null
  }
  if (!state.metaTitle && !state.indexTitle && state.sawSessionMeta) {
    const indexPath = codexIndexPath(context.candidate)
    if (indexPath) {
      state.indexTitle = await findCodexIndexTitle(indexPath, builder.fields.sessionId, context)
    }
  }
  if (!state.metaTitle && state.indexTitle) builder.patch({ title: state.indexTitle })
  return builder.finish({ titleFallback: state.metaTitle ?? state.indexTitle ?? state.userTitle })
}

function numberValue(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0
}

function tokenTotal(value: unknown): number {
  if (!isRecord(value)) return 0
  const total = numberValue(value.total) || numberValue(value.totalTokens) || numberValue(value.total_tokens)
  if (total > 0) return total
  return (
    numberValue(value.input) +
    numberValue(value.inputTokens) +
    numberValue(value.input_tokens) +
    numberValue(value.output) +
    numberValue(value.outputTokens) +
    numberValue(value.output_tokens) +
    numberValue(value.cacheRead) +
    numberValue(value.cacheReadTokens) +
    numberValue(value.cache_read_input_tokens) +
    numberValue(value.cacheWrite) +
    numberValue(value.cacheWriteTokens) +
    numberValue(value.cache_creation_input_tokens) +
    numberValue(value.cached) +
    numberValue(value.cachedInputTokens) +
    numberValue(value.cached_input_tokens) +
    numberValue(value.reasoning) +
    numberValue(value.reasoningOutputTokens) +
    numberValue(value.reasoning_output_tokens)
  )
}

function consumeGeminiMessage(builder: Builder, record: Record<string, unknown>): void {
  if (record.type === 'user') {
    const text = textFromContent(record.content)
    builder.message('user', text, record.timestamp)
    publishContentTools(builder.context, record.content, record.timestamp)
    return
  }
  if (record.type === 'gemini') {
    builder.message('assistant', textFromContent(record.content), record.timestamp)
    publishContentTools(builder.context, record.content, record.timestamp)
    const model = string(record.model)
    if (model) builder.patch({ model })
    const tokens = tokenTotal(record.tokens)
    if (tokens) builder.patch({ totalTokens: tokens })
  }
}

async function parseGeminiJsonl(context: ParserContext): Promise<VaultSession> {
  const builder = newBuilder(context)
  let explicitCwdFound = false
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    const set = isRecord(record.$set) ? record.$set : null
    const explicitCwd = absoluteGeminiCwd(record.cwd) ?? absoluteGeminiCwd(set?.cwd)
    if (!explicitCwdFound && explicitCwd) {
      builder.patch({ cwd: explicitCwd })
      explicitCwdFound = true
    }
    if (set) {
      noteTime(builder, set.lastUpdated)
      continue
    }
    setSessionId(builder, record.sessionId)
    noteTime(builder, record.startTime)
    noteTime(builder, record.lastUpdated)
    consumeGeminiMessage(builder, record)
  }
  return builder.finish()
}

class JsonCharacterReader {
  private readonly iterator: AsyncIterator<Buffer | string>
  private readonly decoder = new StringDecoder('utf8')
  private chunk = ''
  private offset = 0
  private ended = false
  private pending: string | null = null

  constructor(stream: AsyncIterable<Buffer | string>) {
    this.iterator = stream[Symbol.asyncIterator]()
  }

  pushBack(character: string): void {
    if (this.pending !== null) throw new Error('JSON reader pushback overflow')
    this.pending = character
  }

  async next(): Promise<string | null> {
    if (this.pending !== null) {
      const value = this.pending
      this.pending = null
      return value
    }
    while (this.offset >= this.chunk.length) {
      if (this.ended) return null
      const next = await this.iterator.next()
      if (next.done) {
        this.chunk = this.decoder.end()
        this.offset = 0
        this.ended = true
        if (!this.chunk) return null
      } else {
        const value = next.value
        this.chunk = this.decoder.write(typeof value === 'string' ? Buffer.from(value) : value)
        this.offset = 0
      }
    }
    return this.chunk[this.offset++] ?? null
  }
}

type JsonPunctuation = '{' | '}' | '[' | ']' | ':' | ','
type JsonToken = { kind: 'punctuation'; value: JsonPunctuation } | { kind: 'value'; value: unknown }

class JsonTokenReader {
  private readonly chars: JsonCharacterReader
  private readonly context: ParserContext

  constructor(chars: JsonCharacterReader, context: ParserContext) {
    this.chars = chars
    this.context = context
  }

  async next(): Promise<JsonToken | null> {
    throwIfAborted(this.context.signal)
    let character = await this.chars.next()
    while (character !== null && /[\t\n\r ]/.test(character)) character = await this.chars.next()
    if (character === null) return null
    if ('{}[]:,'.includes(character)) {
      return { kind: 'punctuation', value: character as JsonPunctuation }
    }
    if (character === '"') return { kind: 'value', value: await this.readString() }
    if (character === '-' || (character >= '0' && character <= '9')) {
      return { kind: 'value', value: await this.readNumber(character) }
    }
    if (character === 't') return { kind: 'value', value: await this.readLiteral('true', true) }
    if (character === 'f') return { kind: 'value', value: await this.readLiteral('false', false) }
    if (character === 'n') return { kind: 'value', value: await this.readLiteral('null', null) }
    throw new SyntaxError('Invalid JSON token')
  }

  private async readString(): Promise<string> {
    const raw: string[] = ['"']
    let rawLength = 1
    let capture = true
    let escaping = false
    for (;;) {
      const character = await this.chars.next()
      if (character === null) throw new SyntaxError('Unterminated JSON string')
      if (escaping) {
        let sequence = character
        if (character === 'u') {
          for (let index = 0; index < 4; index++) {
            const digit = await this.chars.next()
            if (digit === null || !/[0-9a-f]/i.test(digit)) throw new SyntaxError('Invalid JSON escape')
            sequence += digit
          }
        } else if (!'"\\/bfnrt'.includes(character)) {
          throw new SyntaxError('Invalid JSON escape')
        }
        if (capture) {
          const part = `\\${sequence}`
          if (rawLength + part.length <= MAX_JSON_STRING_RAW_CHARS) {
            raw.push(part)
            rawLength += part.length
          } else {
            capture = false
          }
        }
        escaping = false
        continue
      }
      if (character === '\\') {
        escaping = true
        continue
      }
      if (character === '"') {
        if (capture) raw.push('"')
        return JSON.parse(`${raw.join('')}${capture ? '' : '"'}`) as string
      }
      if (character.charCodeAt(0) < 0x20) throw new SyntaxError('Invalid JSON string character')
      if (capture) {
        if (rawLength + character.length <= MAX_JSON_STRING_RAW_CHARS) {
          raw.push(character)
          rawLength += character.length
        } else {
          capture = false
        }
      }
    }
  }

  private async readNumber(first: string): Promise<number> {
    let raw = first
    for (;;) {
      const character = await this.chars.next()
      if (character === null) break
      if (/[\t\n\r ,\]}]/.test(character)) {
        this.chars.pushBack(character)
        break
      }
      raw += character
      if (raw.length > 128) throw new SyntaxError('Invalid JSON number')
    }
    const value: unknown = JSON.parse(raw)
    if (typeof value !== 'number') throw new SyntaxError('Invalid JSON number')
    return value
  }

  private async readLiteral<T>(literal: string, value: T): Promise<T> {
    for (let index = 1; index < literal.length; index++) {
      if (await this.chars.next() !== literal[index]) throw new SyntaxError('Invalid JSON literal')
    }
    return value
  }
}

const MAX_JSON_STRING_RAW_CHARS = 6 * 256 * 1024 + 2

function expectPunctuation(token: JsonToken | null, expected: JsonPunctuation): void {
  if (token?.kind !== 'punctuation' || token.value !== expected) throw new SyntaxError(`Expected ${expected}`)
}

async function readJsonValue(reader: JsonTokenReader, first?: JsonToken | null): Promise<unknown> {
  const token = first === undefined ? await reader.next() : first
  if (!token) throw new SyntaxError('Unexpected end of JSON')
  if (token.kind === 'value') return token.value
  if (token.value === '{') {
    const value: Record<string, unknown> = Object.create(null)
    let next = await reader.next()
    if (next?.kind === 'punctuation' && next.value === '}') return value
    for (;;) {
      if (next?.kind !== 'value' || typeof next.value !== 'string') throw new SyntaxError('Expected JSON object key')
      expectPunctuation(await reader.next(), ':')
      value[next.value] = await readJsonValue(reader)
      next = await reader.next()
      if (next?.kind === 'punctuation' && next.value === '}') return value
      expectPunctuation(next, ',')
      next = await reader.next()
    }
  }
  if (token.value === '[') {
    const value: unknown[] = []
    let next = await reader.next()
    if (next?.kind === 'punctuation' && next.value === ']') return value
    for (;;) {
      value.push(await readJsonValue(reader, next))
      next = await reader.next()
      if (next?.kind === 'punctuation' && next.value === ']') return value
      expectPunctuation(next, ',')
      next = await reader.next()
    }
  }
  throw new SyntaxError('Expected JSON value')
}

async function skipJsonValue(reader: JsonTokenReader, first?: JsonToken | null): Promise<void> {
  const token = first === undefined ? await reader.next() : first
  if (!token) throw new SyntaxError('Unexpected end of JSON')
  if (token.kind === 'value') return
  if (token.value === '{') {
    let next = await reader.next()
    if (next?.kind === 'punctuation' && next.value === '}') return
    for (;;) {
      if (next?.kind !== 'value' || typeof next.value !== 'string') throw new SyntaxError('Expected JSON object key')
      expectPunctuation(await reader.next(), ':')
      await skipJsonValue(reader)
      next = await reader.next()
      if (next?.kind === 'punctuation' && next.value === '}') return
      expectPunctuation(next, ',')
      next = await reader.next()
    }
  }
  if (token.value === '[') {
    let next = await reader.next()
    if (next?.kind === 'punctuation' && next.value === ']') return
    for (;;) {
      await skipJsonValue(reader, next)
      next = await reader.next()
      if (next?.kind === 'punctuation' && next.value === ']') return
      expectPunctuation(next, ',')
      next = await reader.next()
    }
  }
  throw new SyntaxError('Expected JSON value')
}

async function parseGeminiDocument(context: ParserContext, builder: Builder): Promise<boolean> {
  const stream = createReadStream(context.candidate.filePath, { highWaterMark: 64 * 1024 })
  const abort = () => stream.destroy(context.signal?.reason instanceof Error ? context.signal.reason : new Error('Scan cancelled'))
  context.signal?.addEventListener('abort', abort, { once: true })
  try {
    const reader = new JsonTokenReader(new JsonCharacterReader(stream), context)
    expectPunctuation(await reader.next(), '{')
    let sessionId: string | null = null
    let startTime: unknown = null
    let lastUpdated: unknown = null
    let explicitCwd: string | null = null
    let messageCwd: string | null = null
    let messagesArray = false
    let next = await reader.next()
    if (next?.kind === 'punctuation' && next.value === '}') return false
    for (;;) {
      if (next?.kind !== 'value' || typeof next.value !== 'string') throw new SyntaxError('Expected Gemini session field')
      const key = next.value
      expectPunctuation(await reader.next(), ':')
      const value = await reader.next()
      if (key === 'messages' && value?.kind === 'punctuation' && value.value === '[') {
        messagesArray = true
        let item = await reader.next()
        if (!(item?.kind === 'punctuation' && item.value === ']')) {
          for (;;) {
            const message = await readJsonValue(reader, item)
            if (isRecord(message)) {
              messageCwd ??= absoluteGeminiCwd(message.cwd)
              consumeGeminiMessage(builder, message)
            }
            item = await reader.next()
            if (item?.kind === 'punctuation' && item.value === ']') break
            expectPunctuation(item, ',')
            item = await reader.next()
          }
        }
      } else if (key === 'cwd') {
        explicitCwd = absoluteGeminiCwd(await readJsonValue(reader, value))
      } else if (key === 'sessionId' || key === 'startTime' || key === 'lastUpdated') {
        const field = await readJsonValue(reader, value)
        if (key === 'sessionId') sessionId = string(field)
        else if (key === 'startTime') startTime = field
        else lastUpdated = field
      } else {
        await skipJsonValue(reader, value)
      }
      next = await reader.next()
      if (next?.kind === 'punctuation' && next.value === '}') break
      expectPunctuation(next, ',')
      next = await reader.next()
    }
    if (await reader.next()) throw new SyntaxError('Trailing data after Gemini session')
    if (sessionId) setSessionId(builder, sessionId)
    noteTime(builder, startTime)
    noteTime(builder, lastUpdated)
    const cwd = explicitCwd ?? messageCwd
    if (cwd) builder.patch({ cwd })
    return messagesArray
  } catch (error) {
    throwIfAborted(context.signal)
    if (error instanceof SyntaxError) return false
    throw error
  } finally {
    context.signal?.removeEventListener('abort', abort)
    stream.destroy()
  }
}

async function parseGemini(context: ParserContext): Promise<VaultSession | null> {
  const extension = extname(context.candidate.filePath).toLowerCase()
  if (extension === '.jsonl') return parseGeminiJsonl(context)
  if (extension !== '.json') return null
  const builder = newBuilder(context)
  if (!(await parseGeminiDocument(context, builder))) return null
  return builder.finish()
}

function copilotTrustedFolder(value: unknown): string | null {
  const message = string(value)
  return message?.match(/^Folder (.+) has been added to trusted folders\.$/)?.[1] ?? null
}

async function parseCopilot(context: ParserContext): Promise<VaultSession> {
  const builder = newBuilder(context)
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    noteTime(builder, record.timestamp)
    const data = isRecord(record.data) ? record.data : null
    if (record.type === 'session.start' && data) {
      setSessionId(builder, data.sessionId)
      noteTime(builder, string(data.startTime))
      continue
    }
    if (record.type === 'session.model_change' && data) {
      const model = string(data.newModel)
      if (model) builder.patch({ model })
      continue
    }
    if (record.type === 'session.info' && data) {
      const cwd = copilotTrustedFolder(data.message)
      if (cwd) builder.patch({ cwd })
      continue
    }
    if (record.type === 'user.message' && data) {
      const text = string(data.transformedContent) ?? string(data.content)
      if (!builder.fields.title && text) builder.patch({ title: normalizeTitle(text) })
      builder.message('user', text, record.timestamp)
      continue
    }
    if (record.type === 'assistant.message' && data) {
      builder.message('assistant', string(data.content), record.timestamp)
      continue
    }
    if (record.type === 'session.shutdown' && data) {
      const model = string(data.currentModel)
      if (model) builder.patch({ model })
      const metrics = isRecord(data.modelMetrics) ? data.modelMetrics : null
      let total = numberValue(data.currentTokens)
      if (metrics) {
        for (const metric of Object.values(metrics)) {
          if (isRecord(metric)) total += tokenTotal(metric.usage)
        }
      }
      if (total) builder.patch({ totalTokens: total })
    }
  }
  return builder.finish()
}

function cursorMetaPath(candidate: SourceCandidate): string | null {
  const explicit = string(candidate.metadata?.cursorMetaPath)
  if (explicit) return explicit
  return candidate.sidecars?.find((path) => basename(path) === 'meta.json') ?? null
}

async function readCursorMeta(context: ParserContext): Promise<Record<string, unknown> | null> {
  const path = cursorMetaPath(context.candidate)
  if (!path) return null
  try {
    throwIfAborted(context.signal)
    const value = await readJsonObject(path)
    throwIfAborted(context.signal)
    return value
  } catch {
    throwIfAborted(context.signal)
    return null
  }
}

async function parseCursor(context: ParserContext): Promise<VaultSession> {
  const builder = newBuilder(context)
  let userTitle: string | null = null
  let sawTranscriptTime = false
  for await (const record of readJsonl(context.candidate.filePath, context.signal)) {
    noteTime(builder, record.timestamp)
    if (numberOrDate(record.timestamp) !== null) sawTranscriptTime = true
    const role = string(record.role)
    if (role !== 'user' && role !== 'assistant') continue
    const nested = isRecord(record.message) ? record.message : null
    const content = nested?.content ?? record.content
    const text = textFromContent(content)
    if (role === 'user') {
      const prompt = titleText(nested?.content) ?? titleText(record.content)
      userTitle ??= prompt
      emitUser(builder, text, record.timestamp)
      publishContentTools(context, content, record.timestamp)
    } else {
      builder.message('assistant', text, record.timestamp)
      publishContentTools(context, content, record.timestamp)
    }
  }
  const meta = await readCursorMeta(context)
  const metaTitle = normalizeTitle(string(meta?.title) ?? string(context.candidate.metadata?.title))
  const cwd = string(meta?.cwd)
  if (cwd) builder.patch({ cwd })
  if (meta && !sawTranscriptTime) {
    const createdAt = numberOrDate(meta.createdAtMs)
    const updatedAt = numberOrDate(meta.updatedAtMs)
    if (createdAt !== null) builder.fields.createdAt = createdAt
    if (updatedAt !== null) builder.fields.updatedAt = updatedAt
  }
  return builder.finish({ titleFallback: userTitle ?? builder.firstPromptTitle ?? metaTitle })
}
